// Writes src/hubs/<hub>/frqMeta.js — a small summary of every generated FRQ exam (title, points, rubric points per part)
// that the Dashboard uses to show self-scores without loading the full exam text.
// usage: node tools/frq-authoring/buildmeta.mjs <hub>      (buildfrq.mjs runs this automatically)
import fs from "fs";
import path from "path";
import { fileURLToPath, pathToFileURL } from "url";
const HERE = path.dirname(fileURLToPath(import.meta.url));
const hub = process.argv[2];
const dir = path.resolve(HERE, `../../src/hubs/${hub}/frqExams`);
const files = fs.readdirSync(dir).filter((f) => f.endsWith(".js")).sort();
const meta = {};
for (const f of files) {
  const ex = (await import(pathToFileURL(path.join(dir, f)).href + `?t=${Date.now()}`)).default;
  const parts = {};
  let total = 0;
  ex.questions.forEach((q) => q.parts.forEach((p) => {
    const pts = p.rubric.map((r) => (typeof r === "string" ? 1 : r.pts ?? 1));
    parts[`${q.id}.${p.id}`] = pts;
    total += pts.reduce((a, b) => a + b, 0);
  }));
  meta[ex.id] = { title: ex.title, sample: !!ex.sample, points: total, parts };
}
const order = ["sample", "exam1", "exam2", "exam3", "exam4"].filter((k) => meta[k]);
const ordered = Object.fromEntries(order.map((k) => [k, meta[k]]));
fs.writeFileSync(path.resolve(HERE, `../../src/hubs/${hub}/frqMeta.js`), `// Generated by tools/frq-authoring/buildmeta.mjs — do not edit.\nconst FRQ_META = ${JSON.stringify(ordered)};\n\nexport default FRQ_META;\n`);
console.log(`${hub}: frqMeta.js for ${order.join(", ")}`);
