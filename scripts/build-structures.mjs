// Collects every {{mol:SMILES}} and {{rxn:...}} token in a College Hub course's unit files,
// renders each to SVG, and writes <course>/structures.generated.js.
// Usage: node --import ./scripts/ext-hook.mjs scripts/build-structures.mjs orgchem1 orgchem2
import fs from "node:fs";
import path from "node:path";
import { pathToFileURL } from "node:url";
import { molSvg, rxnSvg } from "./lib/structures.mjs";
import { handSvg } from "./lib/handdrawn.mjs";

const root = path.resolve("src/hubs/college");
const TOKEN = /\{\{(mol|rxn|svg):([\s\S]+?)\}\}/g;

// Strings may hold tokens; block fields mol / rxn / mols expand to tokens in builders.js, so synthesize them here.
function walk(v, f) {
  if (typeof v === "string") f(v);
  else if (Array.isArray(v)) v.forEach((x) => walk(x, f));
  else if (v && typeof v === "object") {
    if (typeof v.mol === "string") f(`{{mol:${v.mol}}}`);
    if (typeof v.rxn === "string") f(`{{rxn:${v.rxn}}}`);
    if (typeof v.svg === "string") f(`{{svg:${v.svg}}}`);
    if (Array.isArray(v.mols)) v.mols.forEach(([smi]) => f(smi.startsWith("svg:") ? `{{${smi}}}` : `{{mol:${smi}}}`));
    Object.values(v).forEach((x) => walk(x, f));
  }
}

for (const course of process.argv.slice(2)) {
  const dir = path.join(root, course);
  const units = fs.readdirSync(dir).filter((f) => /^unit\d+\.js$/.test(f)).sort();
  const map = {};
  let bad = 0;
  for (const f of units) {
    const mod = await import(pathToFileURL(path.join(dir, f)).href + "?t=" + Date.now());
    walk(mod.default, (s) => {
      for (const m of s.matchAll(TOKEN)) {
        const [, kind, spec] = m;
        const key = `${kind}:${spec}`;
        if (map[key]) continue;
        try { map[key] = kind === "mol" ? molSvg(spec.trim()) : kind === "svg" ? handSvg(spec) : rxnSvg(spec); }
        catch (e) { bad++; console.error(`  ! ${course}/${f}: ${key} -> ${e.message}`); }
      }
    });
  }
  const body = `// GENERATED by scripts/build-structures.mjs. Do not edit by hand.\nexport default ${JSON.stringify(map)};\n`;
  fs.writeFileSync(path.join(dir, "structures.generated.js"), body);
  console.log(`${course}: ${Object.keys(map).length} structures, ${bad} errors, ${(body.length / 1024).toFixed(0)} KB`);
}
